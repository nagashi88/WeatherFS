"""SQLAlchemy ORM models for WeatherEdge.

All 11 tables from PRD Section 10, with addendum overrides:
- Gap 9: trades.status uses 'open', 'won', 'lost', 'cancelled', 'abandoned' (not 'sold')
"""

from __future__ import annotations

from datetime import datetime, timezone

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Integer, Text, UniqueConstraint
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class Market(Base):
    """Markets being tracked (Polymarket or Kalshi)."""

    __tablename__ = "markets"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    platform: Mapped[str] = mapped_column(Text, nullable=False)  # 'polymarket' or 'kalshi'
    city: Mapped[str] = mapped_column(Text, nullable=False)
    station: Mapped[str] = mapped_column(Text, nullable=False)
    date: Mapped[str] = mapped_column(Text, nullable=False)  # YYYY-MM-DD
    market_type: Mapped[str] = mapped_column(Text, nullable=False)  # 'daily_high', 'daily_low', 'precipitation'
    threshold_low: Mapped[float | None] = mapped_column(Float)
    threshold_high: Mapped[float | None] = mapped_column(Float)
    resolution_source: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime | None] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc))



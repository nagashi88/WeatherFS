class Signal(Base):
    """Trading signals generated by strategy agents."""

    __tablename__ = "signals"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    market_id: Mapped[str | None] = mapped_column(Text, ForeignKey("markets.id"))
    agent_name: Mapped[str] = mapped_column(Text, nullable=False)
    signal_type: Mapped[str] = mapped_column(Text, nullable=False)  # 'buy_yes', 'buy_no', 'no_trade'
    model_probability: Mapped[float | None] = mapped_column(Float)
    market_price: Mapped[float | None] = mapped_column(Float)
    edge: Mapped[float | None] = mapped_column(Float)
    confidence: Mapped[float | None] = mapped_column(Float)
    reasoning: Mapped[str | None] = mapped_column(Text)
    # Back-link to the resulting trade. NULL when the aggregator chose not to
    # trade or no signal carried this market over threshold. Lets a losing trade
    # JOIN back to every per-agent vote that produced it for post-fact diagnosis.
    trade_id: Mapped[int | None] = mapped_column(Integer, ForeignKey("trades.id"))
    created_at: Mapped[datetime | None] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc))


class Trade(Base):
    """Executed trades (paper and live).

    status values per Addendum Gap 9:
        'open'      — position is open, not yet resolved
        'won'       — market resolved in our favour
        'lost'      — market resolved against us
        'edge_stop' — early exit from edge trailing-stop rule
        'capital_protect' — early risk stop-loss exit
        'time_decay' — time-based early exit near market close
        'ev_based'  — early exit when EV(close) > EV(hold)
        'bucket_invalidated' — early exit when METAR daily_high exceeds bucket_high
                               (YES resolution physically impossible)
        'pending'   — limit order placed but not filled yet
        'cancelled' — unfilled order cancelled (TTL expired or kill switch)
        'abandoned' — filled position abandoned during emergency exit
    """

    __tablename__ = "trades"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    market_id: Mapped[str | None] = mapped_column(Text, ForeignKey("markets.id"))
    platform: Mapped[str] = mapped_column(Text, nullable=False)
    mode: Mapped[str] = mapped_column(Text, nullable=False)  # 'paper' or 'live'
    side: Mapped[str] = mapped_column(Text, nullable=False)  # 'buy_yes' or 'buy_no'
    price: Mapped[float] = mapped_column(Float, nullable=False)
    amount: Mapped[float] = mapped_column(Float, nullable=False)
    cost: Mapped[float] = mapped_column(Float, nullable=False)
    agent_name: Mapped[str | None] = mapped_column(Text)
    model_probability: Mapped[float | None] = mapped_column(Float)
    edge_at_entry: Mapped[float | None] = mapped_column(Float)
    gaussian_prob: Mapped[float | None] = mapped_column(Float)
    ensemble_prob: Mapped[float | None] = mapped_column(Float)
    blended_prob: Mapped[float | None] = mapped_column(Float)
    raw_model_prob: Mapped[float | None] = mapped_column(Float)  # Pre-clamp blended (audit floor effect)
    station: Mapped[str | None] = mapped_column(Text)
    market_date: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, default="open")  # see docstring above
    resolution_value: Mapped[float | None] = mapped_column(Float)  # actual temp/precipitation
    pnl: Mapped[float | None] = mapped_column(Float)
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime)
    created_at: Mapped[datetime | None] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc))
    order_type: Mapped[str | None] = mapped_column(Text, default="market")
    limit_price: Mapped[float | None] = mapped_column(Float)
    forecast_timestamp: Mapped[datetime | None] = mapped_column(DateTime)
    market_price_timestamp: Mapped[datetime | None] = mapped_column(DateTime)
    # True when PortfolioManager reduced this trade's amount to fit available
    # cash (the cap path floors size to 0.01 increments). Replaces the older
    # "amount < 1.0" heuristic in daily_summary so a legitimately small
    # full-size order isn't misreported as a cash-cap event.
    cash_capped: Mapped[bool | None] = mapped_column(Boolean, default=False)
    regime: Mapped[str | None] = mapped_column(Text)


